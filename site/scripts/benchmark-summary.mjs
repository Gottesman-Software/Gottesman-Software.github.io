import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function attributesFromTag(tag) {
  const attributes = {};
  for (const match of tag.matchAll(/([\w-]+)\s*=\s*(["'])(.*?)\2/g)) {
    attributes[match[1]] = match[3];
  }
  return attributes;
}

export function summarizeBenchmarks(html) {
  const records = [...html.matchAll(/<(?:article|tr)\b[^>]*data-benchmark-record=["'][^"']+["'][^>]*>/gi)]
    .map((match) => attributesFromTag(match[0]));

  const count = (kind) => records.filter((record) => record["data-benchmark-record"] === kind).length;
  const verifiedResults = records.filter((record) => (
    record["data-status"] === "verified"
    && Boolean(record["data-evidence-href"]?.trim())
  )).length;

  return {
    researchStreams: count("stream"),
    literatureAnchors: count("literature"),
    publishedResults: count("published-result"),
    peerReviewedResults: records.filter((record) => (
      record["data-benchmark-record"] === "published-result"
      && record["data-publication-tier"] === "peer-reviewed"
    )).length,
    initialHardwareTests: count("hardware-test"),
    verifiedResults,
  };
}

export function formatBenchmarkSummary(summary) {
  return Object.fromEntries(
    Object.entries(summary).map(([key, value]) => [key, String(value).padStart(2, "0")]),
  );
}

async function writeSummary() {
  const sourcePath = path.join(siteRoot, "public", "benchmarks", "index.html");
  const publicPath = path.join(siteRoot, "public", "benchmarks", "summary.json");
  const modulePath = path.join(siteRoot, "src", "benchmark-summary.js");
  const html = await readFile(sourcePath, "utf8");
  const summary = summarizeBenchmarks(html);

  await Promise.all([
    writeFile(publicPath, `${JSON.stringify(summary, null, 2)}\n`),
    writeFile(
      modulePath,
      `// Generated by scripts/benchmark-summary.mjs.\nexport const benchmarkSummary = ${JSON.stringify(formatBenchmarkSummary(summary), null, 2)};\n`,
    ),
  ]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeSummary();
}
